//-----------------------------------------------------------
// Function: Unit test of the AES-128 primitives (aes128_pkg) and of the
//           forward / inverse key expansion modules
//-----------------------------------------------------------
// Independent oracles:
//   * S-box          : exhaustive (256 values, both directions) against the
//                      look-up-table inverse S-box in tb/ref/aes128_sbox_inv_lut.sv
//   * MixColumns     : FIPS-197 column examples + all 32 basis vectors + random
//                      linearity/round-trip (the functions are GF(2)-linear, so
//                      the basis vectors prove InvMix(Mix(x)) = x for ALL x)
//   * Rcon           : generated by repeated xtime
//   * Key expansion  : the 11 round keys of FIPS-197 Appendix A.1, forward and
//                      backwards (round key 10 -> round key 0)
//-----------------------------------------------------------
`timescale 1ns/1ps
module tb_aes128_prim;
  import aes128_pkg::*;
  `include "ref/aes128_sbox_inv_lut.sv"
  //---------------------------------------------------------
  int n_pass = 0;
  int n_fail = 0;
  task automatic chk(input string name, input bit ok);
    if (ok) n_pass++;
    else begin n_fail++; if (n_fail <= 15) $display("FAIL %s", name); end
  endtask
  //---------------------------------------------------------
  // Key expansion DUTs
  //---------------------------------------------------------
  logic clk = 1'b0;
  always #2 clk = ~clk;
  logic         en_f = 1'b0, en_i = 1'b0;
  logic [3:0]   rn_f = 4'd0, rn_i = 4'd0;
  localparam logic [127:0] KEY = 128'h2b7e151628aed2a6abf7158809cf4f3c;
  logic [127:0] RK [0:10];
  wire  [127:0] fk, ik;
  aes128_key_expansion     u_f (.clk_sys(clk), .rst_n(1'b1), .cipher_en(1'b0), .rkey_en(en_f),
                                .cipher_key(KEY), .round_num(rn_f), .round_key_out(fk));
  aes128_key_expansion_inv u_i (.clk_sys(clk), .rst_n(1'b1), .decipher_en(1'b0), .rkey_en(en_i),
                                .round_key_10(RK[10]), .round_num(rn_i), .round_key_inv_out(ik));
  //---------------------------------------------------------
  int x, y, n, r, n9;
  logic [7:0]  fwd, found;
  logic [7:0]  rc;
  logic [31:0] a32, b32, c32;
  logic [31:0] mc_in [0:3], mc_out [0:3];
  initial begin
    RK[0]  = 128'h2b7e151628aed2a6abf7158809cf4f3c;  RK[1]  = 128'ha0fafe1788542cb123a339392a6c7605;
    RK[2]  = 128'hf2c295f27a96b9435935807a7359f67f;  RK[3]  = 128'h3d80477d4716fe3e1e237e446d7a883b;
    RK[4]  = 128'hef44a541a8525b7fb671253bdb0bad00;  RK[5]  = 128'hd4d1c6f87c839d87caf2b8bc11f915bc;
    RK[6]  = 128'h6d88a37a110b3efddbf98641ca0093fd;  RK[7]  = 128'h4e54f70e5f5fc9f384a64fb24ea6dc4f;
    RK[8]  = 128'head27321b58dbad2312bf5607f8d292f;  RK[9]  = 128'hac7766f319fadc2128d12941575c006e;
    RK[10] = 128'hd014f9a8c9ee2589e13f0cc8b6630ca6;
    //-------------------------------------------------------
    // S-box and inverse S-box: exhaustive, independent oracle
    //-------------------------------------------------------
    for (x = 0; x < 256; x++) begin
      chk($sformatf("InvSbox[%02h] vs LUT", x), aes128_sbox(x[7:0], 1'b0) === aes128_sbox_inv(x[7:0]));
      //forward S-box derived from the LUT: the y with InvLUT(y) == x
      found = 8'h00;
      for (y = 0; y < 256; y++) if (aes128_sbox_inv(y[7:0]) == x[7:0]) found = y[7:0];
      chk($sformatf("Sbox[%02h] vs LUT", x), aes128_sbox(x[7:0], 1'b1) === found);
      chk($sformatf("Inv(Sub(%02h))", x), aes128_sbox(aes128_sbox(x[7:0], 1'b1), 1'b0) === x[7:0]);
      chk($sformatf("Sub(Inv(%02h))", x), aes128_sbox(aes128_sbox(x[7:0], 1'b0), 1'b1) === x[7:0]);
    end
    chk("Sbox[00]=63", aes128_sbox(8'h00, 1'b1) === 8'h63);
    chk("Sbox[53]=ed", aes128_sbox(8'h53, 1'b1) === 8'hed);      //FIPS-197 example
    //-------------------------------------------------------
    // MixColumns / InvMixColumns
    //-------------------------------------------------------
    mc_in[0] = 32'hdb135345; mc_out[0] = 32'h8e4da1bc;           //FIPS-197 5.1.3 examples
    mc_in[1] = 32'hf20a225c; mc_out[1] = 32'h9fdc589d;
    mc_in[2] = 32'h01010101; mc_out[2] = 32'h01010101;
    mc_in[3] = 32'hc6c6c6c6; mc_out[3] = 32'hc6c6c6c6;
    for (n = 0; n < 4; n++) begin
      chk($sformatf("mixcol example %0d", n), mixcol(mc_in[n]) === mc_out[n]);
      chk($sformatf("mixcolInv example %0d", n), mixcolInv(mc_out[n]) === mc_in[n]);
    end
    for (n = 0; n < 32; n++) begin
      c32 = 32'd1 << n;
      chk($sformatf("InvMix(Mix(e%0d))", n), mixcolInv(mixcol(c32)) === c32);
      chk($sformatf("Mix(InvMix(e%0d))", n), mixcol(mixcolInv(c32)) === c32);
    end
    for (n = 0; n < 20000; n++) begin
      a32 = $urandom; b32 = $urandom;
      if (mixcol(a32 ^ b32) !== (mixcol(a32) ^ mixcol(b32))) chk("mixcol linearity", 1'b0);
      if (mixcolInv(a32 ^ b32) !== (mixcolInv(a32) ^ mixcolInv(b32))) chk("mixcolInv linearity", 1'b0);
      if (mixcolInv(mixcol(a32)) !== a32) chk("mix round trip", 1'b0);
    end
    chk("mix random loop", 1'b1);
    //-------------------------------------------------------
    // Round constants
    //-------------------------------------------------------
    rc = 8'h01;
    for (n = 0; n < 10; n++) begin
      chk($sformatf("rcon(%0d)", n), aes128_rcon(n[3:0]) === {rc, 24'd0});
      n9 = 9 - n;
      chk($sformatf("rcon_inv(%0d)", n9), aes128_rcon_inv(n9[3:0]) === {rc, 24'd0});
      rc = mul2(rc);
    end
    //-------------------------------------------------------
    // Key expansion: forward 0->10 then inverse 10->0 (real RTL modules)
    //-------------------------------------------------------
    @ (negedge clk);
    en_f = 1'b1; rn_f = 4'd0;
    @ (negedge clk);
    for (r = 0; r < 10; r++) begin
      chk($sformatf("forward round key %0d", r + 1), fk === RK[r + 1]);
      rn_f = r + 1;
      @ (negedge clk);
    end
    en_f = 1'b0;
    en_i = 1'b1; rn_i = 4'd0;
    @ (negedge clk);
    for (r = 0; r < 10; r++) begin
      chk($sformatf("inverse round key %0d", 9 - r), ik === RK[9 - r]);
      rn_i = r + 1;
      @ (negedge clk);
    end
    en_i = 1'b0;
    $display("SUMMARY tb_aes128_prim: checks=%0d pass=%0d fail=%0d", n_pass + n_fail, n_pass, n_fail);
    $display("TEST_RESULT: %s tb_aes128_prim", (n_fail == 0 && n_pass > 0) ? "PASS" : "FAIL");
    if (n_fail != 0 || n_pass == 0) $fatal(1, "tb_aes128_prim FAILED");
    $finish;
  end
endmodule
