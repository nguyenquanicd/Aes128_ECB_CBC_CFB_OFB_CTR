// 2026.10.10 - Rewritten on top of tb/aes128_tb_common.svh: inputs are driven on the
//              falling clock edge (no race with the DUT), X in the output fails the
//              check (the old TB used '!=' and printed PASS for 'xxxx'), the
//              simulation ends with $finish and prints TEST_RESULT.
// Expected values come from NIST SP 800-38A F.2.1 / F.2.2
// (generated by tools/gen_simple_tbs.py; do not edit by hand).
// Compile with the include directory tb/ (-Itb or +incdir+tb).
//-----------------------------------------------------------
`timescale 1ns/1ps
module tb_aes128_cbc;
  `include "aes128_tb_common.svh"
  localparam logic [127:0] KEY = 128'h2b7e151628aed2a6abf7158809cf4f3c;
  localparam logic [127:0] IV  = 128'h000102030405060708090a0b0c0d0e0f;
  logic [127:0] d;
  int lat;
  //One step: run the operation, compare under the mask and print a readable line
  task automatic step(input string label, input bit dec, input logic [3:0] m, input logic [3:0] seg,
                      input bit chain, input logic [127:0] iv_, input logic [127:0] din,
                      input logic [127:0] expv, input logic [127:0] msk);
    int f0;
    f0 = n_fail;
    run_op(dec, m, seg, chain, KEY, iv_, din, d, lat);
    check_eq(label, d, expv, msk);
    $display("----- %-22s data_in=%032h data_out=%032h %s", label, din, d, (n_fail == f0 && lat > 0) ? "PASS" : "FAIL");
  endtask
  //chain_en low for 2 clocks: the next operation starts a new stream
  task automatic new_stream;
    chain_en = 1'b0;
    tick(2);
  endtask
  initial begin
    repeat (4) @ (negedge clk);
    rst_n = 1'b1;
    repeat (2) @ (negedge clk);
    new_stream;
    step("CBC cipher 1", 1'b0, M_CBC, 4'd7, 1'b1, IV, 128'h6bc1bee22e409f96e93d7e117393172a, 128'h7649abac8119b246cee98e9b12e9197d, ALL1);
    step("CBC cipher 2", 1'b0, M_CBC, 4'd7, 1'b1, IV, 128'hae2d8a571e03ac9c9eb76fac45af8e51, 128'h5086cb9b507219ee95db113a917678b2, ALL1);
    step("CBC cipher 3", 1'b0, M_CBC, 4'd7, 1'b1, IV, 128'h30c81c46a35ce411e5fbc1191a0a52ef, 128'h73bed6b8e3c1743b7116e69e22229516, ALL1);
    step("CBC cipher 4", 1'b0, M_CBC, 4'd7, 1'b1, IV, 128'hf69f2445df4f9b17ad2b417be66c3710, 128'h3ff1caa1681fac09120eca307586e1a7, ALL1);
    new_stream;
    step("CBC decipher 1", 1'b1, M_CBC, 4'd7, 1'b1, IV, 128'h7649abac8119b246cee98e9b12e9197d, 128'h6bc1bee22e409f96e93d7e117393172a, ALL1);
    step("CBC decipher 2", 1'b1, M_CBC, 4'd7, 1'b1, IV, 128'h5086cb9b507219ee95db113a917678b2, 128'hae2d8a571e03ac9c9eb76fac45af8e51, ALL1);
    step("CBC decipher 3", 1'b1, M_CBC, 4'd7, 1'b1, IV, 128'h73bed6b8e3c1743b7116e69e22229516, 128'h30c81c46a35ce411e5fbc1191a0a52ef, ALL1);
    step("CBC decipher 4", 1'b1, M_CBC, 4'd7, 1'b1, IV, 128'h3ff1caa1681fac09120eca307586e1a7, 128'hf69f2445df4f9b17ad2b417be66c3710, ALL1);
    tick(3);
    report("tb_aes128_cbc");
  end
  initial begin
    #2000000;
    $display("GLOBAL WATCHDOG");
    $display("TEST_RESULT: FAIL watchdog tb_aes128_cbc");
    $fatal(1, "watchdog");
  end
endmodule
