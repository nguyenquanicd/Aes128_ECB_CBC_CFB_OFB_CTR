"""Generate the six readable per-mode testbenches in simpleTestcase/.

Every constant comes from tools/aes_ref.py (validated against NIST SP 800-38A / FIPS-197),
so the testbenches contain explicit, human-readable known-answer tests without typos.

usage: python gen_simple_tbs.py        (writes ../simpleTestcase/tb_aes128_<mode>.sv)
"""
import os
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[2] / "shared"))
import aes_ref as g

K = g.h2i('2b7e151628aed2a6abf7158809cf4f3c')
IV = g.h2i('000102030405060708090a0b0c0d0e0f')
CTR_IV = g.h2i('f0f1f2f3f4f5f6f7f8f9fafbfcfdfeff')
P = [g.h2i('6bc1bee22e409f96e93d7e117393172a'), g.h2i('ae2d8a571e03ac9c9eb76fac45af8e51'),
     g.h2i('30c81c46a35ce411e5fbc1191a0a52ef'), g.h2i('f69f2445df4f9b17ad2b417be66c3710')]
MODE_NAME = {'ECB': 'M_ECB', 'CBC': 'M_CBC', 'CFB': 'M_CFB', 'OFB': 'M_OFB', 'CTR': 'M_CTR'}


def h(v):
    return "128'h%032x" % v


HEADER = """//-----------------------------------------------------------
// Function: Simple known-answer test for {title}
//-----------------------------------------------------------
// Author: Nguyen Hung Quan
// Website: http://nguyenquanicd.blogspot.com/
//-----------------------------------------------------------
// History:
// 2019.10.22 - First version (ECB)
// 2026.10.10 - Rewritten on top of tb/aes128_tb_common.svh: inputs are driven on the
//              falling clock edge (no race with the DUT), X in the output fails the
//              check (the old TB used '!=' and printed PASS for 'xxxx'), the
//              simulation ends with $finish and prints TEST_RESULT.
// Expected values come from {source}
// (generated by tools/gen_simple_tbs.py; do not edit by hand).
// Compile with the include directory tb/ (-Itb or +incdir+tb).
//-----------------------------------------------------------
`timescale 1ns/1ps
module tb_aes128_{name};
  `include "aes128_tb_common.svh"
  localparam logic [127:0] KEY = {key};
  localparam logic [127:0] IV  = {iv};
  logic [127:0] d;
  int lat;
  //One step: run the operation, compare under the mask and print a readable line
  task automatic step(input string label, input bit dec, input logic [3:0] m, input logic [3:0] seg,
                      input bit chain, input logic [127:0] iv_, input logic [127:0] din,
                      input logic [127:0] expv, input logic [127:0] msk);
    int f0;
    f0 = n_fail;
    run_op(dec, m, seg, chain, KEY, iv_, din, d, lat);
    check_eq(label, d, expv, msk);
    $display("----- %-22s data_in=%032h data_out=%032h %s", label, din, d, (n_fail == f0 && lat > 0) ? "PASS" : "FAIL");
  endtask
  //chain_en low for 2 clocks: the next operation starts a new stream
  task automatic new_stream;
    chain_en = 1'b0;
    tick(2);
  endtask
  initial begin
    repeat (4) @ (negedge clk);
    rst_n = 1'b1;
    repeat (2) @ (negedge clk);
"""

FOOTER = """    tick(3);
    report("tb_aes128_{name}");
  end
  initial begin
    #2000000;
    $display("GLOBAL WATCHDOG");
    $display("TEST_RESULT: FAIL watchdog tb_aes128_{name}");
    $fatal(1, "watchdog");
  end
endmodule
"""


def line(label, dec, mode, seg, chain, iv, din, exp, mask):
    mask_s = 'ALL1' if mask == g.MASK128 else h(mask)
    return '    step("%s", 1\'b%d, %s, 4\'d%d, 1\'b%d, %s, %s, %s, %s);\n' % (
        label, dec, MODE_NAME[mode], seg, chain, 'IV' if iv == IV else h(iv), h(din), h(exp), mask_s)


def stream_lines(label, mode, dec, iv, blocks, seg, chain=1):
    res = g.run_stream(mode, dec, K, iv, blocks, seg)
    out = ['    new_stream;\n']
    for i, (din, exp, mask, ivop) in enumerate(res):
        out.append(line('%s %d' % (label, i + 1), dec, mode, seg, chain, ivop, din, exp, mask))
    return out


def seg_blocks(nseg, seg):
    s = g.SEG_BITS[seg]
    bits = bin(g.b2i(b''.join(g.i2b(x) for x in P)))[2:].zfill(512)
    return [int(bits[i * s:(i + 1) * s], 2) << (128 - s) for i in range(nseg)]


def write(name, title, source, body):
    path = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'simpleTestcase', 'tb_aes128_%s.sv' % name)
    with open(path, 'w', newline='\n') as f:
        f.write(HEADER.format(title=title, source=source, name=name, key=h(K), iv=h(IV)))
        f.write(''.join(body))
        f.write(FOOTER.format(name=name))
    print('wrote', os.path.normpath(path))


def main():
    g.self_test()
    # ECB: single-shot (chain_en=0) and chained
    ecb = []
    for chain in (0, 1):
        for dec in (0, 1):
            enc = g.run_stream('ECB', 0, K, IV, P)
            blocks = P if not dec else [e[1] for e in enc]
            ecb += stream_lines('ECB %s chain_en=%d' % ('decipher' if dec else 'cipher', chain), 'ECB', dec, IV, blocks, 7, chain)
    write('ecb', 'ECB mode', 'NIST SP 800-38A F.1.1 / F.1.2', ecb)
    # CBC
    cbc = []
    for dec in (0, 1):
        enc = g.run_stream('CBC', 0, K, IV, P)
        cbc += stream_lines('CBC %s' % ('decipher' if dec else 'cipher'), 'CBC', dec, IV, P if not dec else [e[1] for e in enc], 7)
    write('cbc', 'CBC mode', 'NIST SP 800-38A F.2.1 / F.2.2', cbc)
    # CFB cipher / decipher: CFB1, CFB8, CFB128 are NIST; the other segment sizes come from the reference model
    for name, dec in (('cfb_cipher', 0), ('cfb_decipher', 1)):
        body = []
        for seg, nseg, nist in ((0, 16, 'NIST F.3.1/F.3.2'), (3, 16, 'NIST F.3.7/F.3.8'), (7, 4, 'NIST F.3.13/F.3.14'),
                                (1, 8, 'reference model'), (2, 8, 'reference model'), (4, 8, 'reference model'),
                                (5, 4, 'reference model'), (6, 4, 'reference model')):
            blocks = seg_blocks(nseg, seg)
            if dec:
                enc = g.run_stream('CFB', 0, K, IV, blocks, seg)
                blocks = [e[1] & e[2] for e in enc]
            body.append('    //CFB%d (%s)\n' % (g.SEG_BITS[seg], nist))
            body += stream_lines('CFB%d %s' % (g.SEG_BITS[seg], 'dec' if dec else 'enc'), 'CFB', dec, IV, blocks, seg)
        write(name, 'CFB mode, %s of every segment size (1,2,4,8,16,32,64,128 bits)' % ('deciphering' if dec else 'ciphering'),
              'NIST SP 800-38A F.3.x (segments 1, 8, 128) and tools/aes_ref.py (others)', body)
    # OFB
    ofb = []
    for dec in (0, 1):
        enc = g.run_stream('OFB', 0, K, IV, P)
        ofb += stream_lines('OFB %s' % ('decipher' if dec else 'cipher'), 'OFB', dec, IV, P if not dec else [e[1] for e in enc], 7)
    write('ofb', 'OFB mode', 'NIST SP 800-38A F.4.1 / F.4.2', ofb)
    # CTR (the host supplies the counter block on init_vector for every block)
    ctr = []
    for dec in (0, 1):
        enc = g.run_stream('CTR', 0, K, CTR_IV, P)
        ctr += stream_lines('CTR %s' % ('decipher' if dec else 'cipher'), 'CTR', dec, CTR_IV, P if not dec else [e[1] for e in enc], 7)
    write('ctr', 'CTR mode (counter block supplied by the host on init_vector)', 'NIST SP 800-38A F.5.1 / F.5.2', ctr)


if __name__ == '__main__':
    main()
