// 2026.10.10 - Rewritten on top of tb/aes128_tb_common.svh: inputs are driven on the
//              falling clock edge (no race with the DUT), X in the output fails the
//              check (the old TB used '!=' and printed PASS for 'xxxx'), the
//              simulation ends with $finish and prints TEST_RESULT.
// Expected values come from NIST SP 800-38A F.1.1 / F.1.2
// (generated by tools/gen_simple_tbs.py; do not edit by hand).
// Compile with the include directory tb/ (-Itb or +incdir+tb).
//-----------------------------------------------------------
`timescale 1ns/1ps
module tb_aes128_ecb;
  `include "aes128_tb_common.svh"
  localparam logic [127:0] KEY = 128'h2b7e151628aed2a6abf7158809cf4f3c;
  localparam logic [127:0] IV  = 128'h000102030405060708090a0b0c0d0e0f;
  logic [127:0] d;
  int lat;
  //One step: run the operation, compare under the mask and print a readable line
  task automatic step(input string label, input bit dec, input logic [3:0] m, input logic [3:0] seg,
                      input bit chain, input logic [127:0] iv_, input logic [127:0] din,
                      input logic [127:0] expv, input logic [127:0] msk);
    int f0;
    f0 = n_fail;
    run_op(dec, m, seg, chain, KEY, iv_, din, d, lat);
    check_eq(label, d, expv, msk);
    $display("----- %-22s data_in=%032h data_out=%032h %s", label, din, d, (n_fail == f0 && lat > 0) ? "PASS" : "FAIL");
  endtask
  //chain_en low for 2 clocks: the next operation starts a new stream
  task automatic new_stream;
    chain_en = 1'b0;
    tick(2);
  endtask
  initial begin
    repeat (4) @ (negedge clk);
    rst_n = 1'b1;
    repeat (2) @ (negedge clk);
    new_stream;
    step("ECB cipher chain_en=0 1", 1'b0, M_ECB, 4'd7, 1'b0, IV, 128'h6bc1bee22e409f96e93d7e117393172a, 128'h3ad77bb40d7a3660a89ecaf32466ef97, ALL1);
    step("ECB cipher chain_en=0 2", 1'b0, M_ECB, 4'd7, 1'b0, IV, 128'hae2d8a571e03ac9c9eb76fac45af8e51, 128'hf5d3d58503b9699de785895a96fdbaaf, ALL1);
    step("ECB cipher chain_en=0 3", 1'b0, M_ECB, 4'd7, 1'b0, IV, 128'h30c81c46a35ce411e5fbc1191a0a52ef, 128'h43b1cd7f598ece23881b00e3ed030688, ALL1);
    step("ECB cipher chain_en=0 4", 1'b0, M_ECB, 4'd7, 1'b0, IV, 128'hf69f2445df4f9b17ad2b417be66c3710, 128'h7b0c785e27e8ad3f8223207104725dd4, ALL1);
    new_stream;
    step("ECB decipher chain_en=0 1", 1'b1, M_ECB, 4'd7, 1'b0, IV, 128'h3ad77bb40d7a3660a89ecaf32466ef97, 128'h6bc1bee22e409f96e93d7e117393172a, ALL1);
    step("ECB decipher chain_en=0 2", 1'b1, M_ECB, 4'd7, 1'b0, IV, 128'hf5d3d58503b9699de785895a96fdbaaf, 128'hae2d8a571e03ac9c9eb76fac45af8e51, ALL1);
    step("ECB decipher chain_en=0 3", 1'b1, M_ECB, 4'd7, 1'b0, IV, 128'h43b1cd7f598ece23881b00e3ed030688, 128'h30c81c46a35ce411e5fbc1191a0a52ef, ALL1);
    step("ECB decipher chain_en=0 4", 1'b1, M_ECB, 4'd7, 1'b0, IV, 128'h7b0c785e27e8ad3f8223207104725dd4, 128'hf69f2445df4f9b17ad2b417be66c3710, ALL1);
    new_stream;
    step("ECB cipher chain_en=1 1", 1'b0, M_ECB, 4'd7, 1'b1, IV, 128'h6bc1bee22e409f96e93d7e117393172a, 128'h3ad77bb40d7a3660a89ecaf32466ef97, ALL1);
    step("ECB cipher chain_en=1 2", 1'b0, M_ECB, 4'd7, 1'b1, IV, 128'hae2d8a571e03ac9c9eb76fac45af8e51, 128'hf5d3d58503b9699de785895a96fdbaaf, ALL1);
    step("ECB cipher chain_en=1 3", 1'b0, M_ECB, 4'd7, 1'b1, IV, 128'h30c81c46a35ce411e5fbc1191a0a52ef, 128'h43b1cd7f598ece23881b00e3ed030688, ALL1);
    step("ECB cipher chain_en=1 4", 1'b0, M_ECB, 4'd7, 1'b1, IV, 128'hf69f2445df4f9b17ad2b417be66c3710, 128'h7b0c785e27e8ad3f8223207104725dd4, ALL1);
    new_stream;
    step("ECB decipher chain_en=1 1", 1'b1, M_ECB, 4'd7, 1'b1, IV, 128'h3ad77bb40d7a3660a89ecaf32466ef97, 128'h6bc1bee22e409f96e93d7e117393172a, ALL1);
    step("ECB decipher chain_en=1 2", 1'b1, M_ECB, 4'd7, 1'b1, IV, 128'hf5d3d58503b9699de785895a96fdbaaf, 128'hae2d8a571e03ac9c9eb76fac45af8e51, ALL1);
    step("ECB decipher chain_en=1 3", 1'b1, M_ECB, 4'd7, 1'b1, IV, 128'h43b1cd7f598ece23881b00e3ed030688, 128'h30c81c46a35ce411e5fbc1191a0a52ef, ALL1);
    step("ECB decipher chain_en=1 4", 1'b1, M_ECB, 4'd7, 1'b1, IV, 128'h7b0c785e27e8ad3f8223207104725dd4, 128'hf69f2445df4f9b17ad2b417be66c3710, ALL1);
    tick(3);
    report("tb_aes128_ecb");
  end
  initial begin
    #2000000;
    $display("GLOBAL WATCHDOG");
    $display("TEST_RESULT: FAIL watchdog tb_aes128_ecb");
    $fatal(1, "watchdog");
  end
endmodule
