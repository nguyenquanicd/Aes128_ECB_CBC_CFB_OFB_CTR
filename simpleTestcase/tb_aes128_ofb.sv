// 2026.10.10 - Rewritten on top of tb/aes128_tb_common.svh: inputs are driven on the
//              falling clock edge (no race with the DUT), X in the output fails the
//              check (the old TB used '!=' and printed PASS for 'xxxx'), the
//              simulation ends with $finish and prints TEST_RESULT.
// Expected values come from NIST SP 800-38A F.4.1 / F.4.2
// (generated by tools/gen_simple_tbs.py; do not edit by hand).
// Compile with the include directory tb/ (-Itb or +incdir+tb).
//-----------------------------------------------------------
`timescale 1ns/1ps
module tb_aes128_ofb;
  `include "aes128_tb_common.svh"
  localparam logic [127:0] KEY = 128'h2b7e151628aed2a6abf7158809cf4f3c;
  localparam logic [127:0] IV  = 128'h000102030405060708090a0b0c0d0e0f;
  logic [127:0] d;
  int lat;
  //One step: run the operation, compare under the mask and print a readable line
  task automatic step(input string label, input bit dec, input logic [3:0] m, input logic [3:0] seg,
                      input bit chain, input logic [127:0] iv_, input logic [127:0] din,
                      input logic [127:0] expv, input logic [127:0] msk);
    int f0;
    f0 = n_fail;
    run_op(dec, m, seg, chain, KEY, iv_, din, d, lat);
    check_eq(label, d, expv, msk);
    $display("----- %-22s data_in=%032h data_out=%032h %s", label, din, d, (n_fail == f0 && lat > 0) ? "PASS" : "FAIL");
  endtask
  //chain_en low for 2 clocks: the next operation starts a new stream
  task automatic new_stream;
    chain_en = 1'b0;
    tick(2);
  endtask
  initial begin
    repeat (4) @ (negedge clk);
    rst_n = 1'b1;
    repeat (2) @ (negedge clk);
    new_stream;
    step("OFB cipher 1", 1'b0, M_OFB, 4'd7, 1'b1, IV, 128'h6bc1bee22e409f96e93d7e117393172a, 128'h3b3fd92eb72dad20333449f8e83cfb4a, ALL1);
    step("OFB cipher 2", 1'b0, M_OFB, 4'd7, 1'b1, IV, 128'hae2d8a571e03ac9c9eb76fac45af8e51, 128'h7789508d16918f03f53c52dac54ed825, ALL1);
    step("OFB cipher 3", 1'b0, M_OFB, 4'd7, 1'b1, IV, 128'h30c81c46a35ce411e5fbc1191a0a52ef, 128'h9740051e9c5fecf64344f7a82260edcc, ALL1);
    step("OFB cipher 4", 1'b0, M_OFB, 4'd7, 1'b1, IV, 128'hf69f2445df4f9b17ad2b417be66c3710, 128'h304c6528f659c77866a510d9c1d6ae5e, ALL1);
    new_stream;
    step("OFB decipher 1", 1'b1, M_OFB, 4'd7, 1'b1, IV, 128'h3b3fd92eb72dad20333449f8e83cfb4a, 128'h6bc1bee22e409f96e93d7e117393172a, ALL1);
    step("OFB decipher 2", 1'b1, M_OFB, 4'd7, 1'b1, IV, 128'h7789508d16918f03f53c52dac54ed825, 128'hae2d8a571e03ac9c9eb76fac45af8e51, ALL1);
    step("OFB decipher 3", 1'b1, M_OFB, 4'd7, 1'b1, IV, 128'h9740051e9c5fecf64344f7a82260edcc, 128'h30c81c46a35ce411e5fbc1191a0a52ef, ALL1);
    step("OFB decipher 4", 1'b1, M_OFB, 4'd7, 1'b1, IV, 128'h304c6528f659c77866a510d9c1d6ae5e, 128'hf69f2445df4f9b17ad2b417be66c3710, ALL1);
    tick(3);
    report("tb_aes128_ofb");
  end
  initial begin
    #2000000;
    $display("GLOBAL WATCHDOG");
    $display("TEST_RESULT: FAIL watchdog tb_aes128_ofb");
    $fatal(1, "watchdog");
  end
endmodule
